import { fontStack, googleFontsHref, googleFontsLinks, MONO_FONTS } from "./fonts.js";
import type { ArtDirection, DesignTokens, FluidStep, FontSpec } from "./types.js";

export const FLUID_MIN_VW = 375;
export const FLUID_MAX_VW = 1440;

const rem = (px: number) => `${+(px / 16).toFixed(4)}rem`;

/** Fluid clamp() between FLUID_MIN_VW and FLUID_MAX_VW. */
export function fluidClamp(minPx: number, maxPx: number, minVw = FLUID_MIN_VW, maxVw = FLUID_MAX_VW): string {
  if (Math.abs(maxPx - minPx) < 0.01) return rem(maxPx);
  const slope = (maxPx - minPx) / (maxVw - minVw);
  const intercept = minPx - slope * minVw;
  const lo = Math.min(minPx, maxPx), hi = Math.max(minPx, maxPx);
  return `clamp(${rem(lo)}, ${rem(intercept)} + ${+(slope * 100).toFixed(4)}vw, ${rem(hi)})`;
}

/**
 * Fluid type steps -1..5. Max sizes are the direction's scale; mobile sizes use a compressed ratio so huge
 * display steps shrink more than body text (keeps hierarchy without overflow at 375px).
 */
export function fluidTypeScale(scale: number[], ratio?: number, displayWidthEm = 0.55): FluidStep[] {
  const base = scale[1] ?? 16;
  const r = ratio ?? (scale[2] && scale[1] ? scale[2] / scale[1] : 1.25);
  const minRatio = 1 + (r - 1) * 0.6;
  const minBase = Math.max(15, base * 0.94);
  // Extended display faces need smaller phone sizes to keep ~8 characters per line at 375px.
  const widthFix = Math.min(1, 0.6 / displayWidthEm);
  return scale.slice(0, 7).map((maxPx, i) => {
    const step = i - 1;
    const fix = step >= 2 ? widthFix : 1;
    const minPx = Math.min(maxPx, Math.round(minBase * minRatio ** step * fix * 100) / 100);
    return { step, minPx, maxPx, clamp: fluidClamp(minPx, maxPx) };
  });
}

export function tokensFromDirection(d: ArtDirection): DesignTokens {
  const mono: FontSpec = d.typography.mono ?? MONO_FONTS.jetbrains!;
  const p = d.palette;
  return {
    name: d.name,
    scheme: p.scheme,
    color: { bg: p.bg, surface: p.surface, text: p.text, muted: p.muted, accent: p.accent, accent2: p.accent2, border: p.border, onAccent: p.onAccent },
    colorOklch: p.oklch,
    font: { display: fontStack(d.typography.display), body: fontStack(d.typography.body), mono: fontStack(mono) },
    fonts: [d.typography.display, d.typography.body, mono],
    type: fluidTypeScale(d.typography.scale, d.typography.ratio, d.typography.display.widthEm),
    tracking: d.typography.tracking,
    space: d.spacing.slice(0, 10),
    radius: d.radius.slice(0, 3),
    radiusButton: d.buttonRadius ?? d.radius[1] ?? 8,
    motion: {
      language: d.motion.language,
      ease: d.motion.easing,
      durFast: d.motion.durations.fast,
      durBase: d.motion.durations.base,
      durSlow: d.motion.durations.slow,
      stagger: d.motion.stagger,
      distance: d.motion.distance,
    },
    grid: { columns: d.grid.columns, maxWidth: d.grid.maxWidth, gutter: d.grid.gutter, margin: d.grid.margin },
  };
}

const COLOR_VARS: Array<[keyof DesignTokens["color"], string]> = [
  ["bg", "--color-bg"],
  ["surface", "--color-surface"],
  ["text", "--color-text"],
  ["muted", "--color-muted"],
  ["accent", "--color-accent"],
  ["accent2", "--color-accent-2"],
  ["border", "--color-border"],
  ["onAccent", "--color-on-accent"],
];

/** CSS custom properties for the tokens (hex base + OKLCH where supported + reduced-motion override). */
export function tokensToCss(t: DesignTokens): string {
  const lines: string[] = [];
  lines.push(`/* Design tokens: ${t.name} (generated by @forge/design) */`);
  lines.push(":root {");
  lines.push(`  color-scheme: ${t.scheme};`);
  for (const [k, v] of COLOR_VARS) lines.push(`  ${v}: ${t.color[k]};`);
  lines.push(`  --font-display: ${t.font.display};`);
  lines.push(`  --font-body: ${t.font.body};`);
  lines.push(`  --font-mono: ${t.font.mono};`);
  lines.push(`  --tracking-display: ${t.tracking.display}em;`);
  lines.push(`  --tracking-body: ${t.tracking.body}em;`);
  for (const s of t.type) lines.push(`  --step-${s.step}: ${s.clamp};`);
  t.space.forEach((v, i) => lines.push(`  --space-${i + 1}: ${rem(v)};`));
  t.radius.forEach((v, i) => lines.push(`  --radius-${i + 1}: ${v >= 999 ? "999px" : rem(v)};`));
  lines.push(`  --radius-button: ${t.radiusButton >= 999 ? "999px" : rem(t.radiusButton)};`);
  lines.push(`  --ease: ${t.motion.ease};`);
  lines.push(`  --dur-fast: ${t.motion.durFast}ms;`);
  lines.push(`  --dur-base: ${t.motion.durBase}ms;`);
  lines.push(`  --dur-slow: ${t.motion.durSlow}ms;`);
  lines.push(`  --stagger: ${t.motion.stagger}ms;`);
  lines.push(`  --distance: ${t.motion.distance}px;`);
  lines.push(`  --grid-columns: ${t.grid.columns};`);
  lines.push(`  --grid-max: ${rem(t.grid.maxWidth)};`);
  lines.push(`  --grid-gutter: ${rem(t.grid.gutter)};`);
  lines.push(`  --grid-margin: clamp(1rem, 4vw, ${rem(t.grid.margin)});`);
  lines.push("}");
  const ok = COLOR_VARS.filter(([k]) => t.colorOklch[k]);
  if (ok.length) {
    lines.push("@supports (color: oklch(0% 0 0)) {");
    lines.push("  :root {");
    for (const [k, v] of ok) lines.push(`    ${v}: ${t.colorOklch[k]};`);
    lines.push("  }");
    lines.push("}");
  }
  lines.push("@media (prefers-reduced-motion: reduce) {");
  lines.push("  :root { --dur-fast: 0ms; --dur-base: 0ms; --dur-slow: 0ms; --stagger: 0ms; --distance: 0px; }");
  lines.push("}");
  return lines.join("\n") + "\n";
}

/** Tailwind preset (v3 `presets: [...]` / v4 via `@config`) mapping utilities onto the CSS variables. */
export function tokensToTailwind(t: DesignTokens): Record<string, unknown> {
  const colors = Object.fromEntries(COLOR_VARS.map(([k, v]) => [k === "accent2" ? "accent-2" : k === "onAccent" ? "on-accent" : k, `var(${v})`]));
  const fontSize = Object.fromEntries(t.type.map((s) => [`step-${s.step}`, `var(--step-${s.step})`]));
  const spacing = Object.fromEntries(t.space.map((_, i) => [`s${i + 1}`, `var(--space-${i + 1})`]));
  return {
    darkMode: "media",
    theme: {
      extend: {
        colors,
        fontFamily: { display: "var(--font-display)", body: "var(--font-body)", mono: "var(--font-mono)" },
        fontSize,
        spacing,
        borderRadius: { 1: "var(--radius-1)", 2: "var(--radius-2)", 3: "var(--radius-3)", button: "var(--radius-button)" },
        transitionTimingFunction: { brand: "var(--ease)" },
        transitionDuration: { fast: "var(--dur-fast)", base: "var(--dur-base)", slow: "var(--dur-slow)" },
        maxWidth: { grid: "var(--grid-max)" },
        letterSpacing: { display: "var(--tracking-display)" },
      },
    },
  };
}

/** W3C Design Tokens Community Group (DTCG) JSON. */
export function tokensToJson(t: DesignTokens): Record<string, unknown> {
  const color = Object.fromEntries(COLOR_VARS.map(([k]) => [k, { $type: "color", $value: t.color[k], ...(t.colorOklch[k] ? { $extensions: { oklch: t.colorOklch[k] } } : {}) }]));
  return {
    $description: `Design tokens for ${t.name} (generated by @forge/design)`,
    color,
    font: Object.fromEntries(Object.entries(t.font).map(([k, v]) => [k, { $type: "fontFamily", $value: v }])),
    type: Object.fromEntries(t.type.map((s) => [`step-${s.step}`, { $type: "dimension", $value: `${s.maxPx}px`, $extensions: { minPx: s.minPx, clamp: s.clamp } }])),
    space: Object.fromEntries(t.space.map((v, i) => [`${i + 1}`, { $type: "dimension", $value: `${v}px` }])),
    radius: {
      ...Object.fromEntries(t.radius.map((v, i) => [`${i + 1}`, { $type: "dimension", $value: `${v}px` }])),
      button: { $type: "dimension", $value: `${t.radiusButton}px` },
    },
    motion: {
      ease: { $type: "cubicBezier", $value: parseBezier(t.motion.ease) ?? t.motion.ease },
      "dur-fast": { $type: "duration", $value: `${t.motion.durFast}ms` },
      "dur-base": { $type: "duration", $value: `${t.motion.durBase}ms` },
      "dur-slow": { $type: "duration", $value: `${t.motion.durSlow}ms` },
    },
    grid: { $type: "other", $value: t.grid },
    scheme: { $type: "other", $value: t.scheme },
  };
}

function parseBezier(s: string): number[] | null {
  const m = /cubic-bezier\(([^)]+)\)/.exec(s);
  if (!m) return null;
  const n = m[1]!.split(",").map((x) => Number(x.trim()));
  return n.length === 4 && n.every((x) => Number.isFinite(x)) ? n : null;
}

export interface SlideTokens {
  /** Hex without '#', as PPTX/pptxgenjs expects ("RRGGBB"). */
  colors: { bg: string; surface: string; text: string; muted: string; accent: string; accent2: string; border: string; onAccent: string };
  fonts: { heading: string; body: string; mono: string };
  /** Point sizes for title/subtitle/body/caption at 16:9. */
  sizes: { title: number; subtitle: number; body: number; caption: number };
  scheme: "light" | "dark";
}

/** Tokens for decks (pptx): hex colours + font family names + pt sizes. */
export function tokensForSlides(t: DesignTokens): SlideTokens {
  const strip = (h: string) => h.replace("#", "").toUpperCase();
  const fam = (stack: string) => stack.split(",")[0]!.replace(/"/g, "").trim();
  return {
    colors: Object.fromEntries(Object.entries(t.color).map(([k, v]) => [k, strip(v)])) as SlideTokens["colors"],
    fonts: { heading: fam(t.font.display), body: fam(t.font.body), mono: fam(t.font.mono) },
    sizes: { title: 44, subtitle: 24, body: 16, caption: 11 },
    scheme: t.scheme,
  };
}

/** Prompt suffix that keeps generated images/video consistent with the art direction. */
export function styleSuffixForMedia(d: ArtDirection): string {
  const p = d.palette;
  const light = p.scheme === "dark" ? "low-key lighting, deep shadows, luminous highlights" : "high-key natural daylight, soft shadows";
  return [
    `art direction "${d.name}": ${d.mood}`,
    `colour palette ${p.bg} background, ${p.accent} and ${p.accent2} accents, ${p.text} for darkest/lightest tones`,
    light,
    `motion feel: ${d.motion.language.toLowerCase()}`,
    "editorial composition with generous negative space, cohesive colour grade",
    "no text, no logos, no watermarks",
  ].join("; ");
}

/** Google Fonts helpers bound to tokens. */
export function fontLinksForTokens(t: DesignTokens): { href: string | null; html: string } {
  return { href: googleFontsHref(t.fonts), html: googleFontsLinks(t.fonts) };
}
