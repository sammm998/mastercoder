/** Naming helpers shared by the mock builder's generators (deterministic, ASCII only). */

export const HEADER = "Generated by Forge mock builder (rule-based, offline)";
export const TS_HEADER = `// ${HEADER}`;
export const PY_HEADER = `# ${HEADER}`;
export const SQL_HEADER = `-- ${HEADER}`;

export function words(s: string): string[] {
  return s
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w.toLowerCase());
}

export const pascal = (s: string): string => words(s).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("") || "Item";
export const camel = (s: string): string => {
  const p = pascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
};
export const kebab = (s: string): string => words(s).join("-") || "item";
export const snake = (s: string): string => words(s).join("_") || "item";
/** "booking" → "Booking", "keyResult" → "Key result". */
export const label = (s: string): string => {
  const w = words(s);
  if (w[w.length - 1] === "id" && w.length > 1) w.pop();
  const t = w.join(" ");
  return t.charAt(0).toUpperCase() + t.slice(1);
};

/** English plural of the last word (enough for entity names). */
export function pluralWord(w: string): string {
  if (/[^aeiou]y$/i.test(w)) return `${w.slice(0, -1)}ies`;
  if (/(s|x|z|ch|sh)$/i.test(w)) return `${w}es`;
  return `${w}s`;
}

export function plural(name: string): string {
  const m = /^(.*?)([A-Z]?[a-z0-9]+)$/.exec(name);
  if (!m) return pluralWord(name);
  return `${m[1] ?? ""}${pluralWord(m[2] ?? name)}`;
}

/** Quote a value as a TS/JS string literal. */
export const q = (s: string): string => JSON.stringify(s);

/** Escape text for JSX children. */
export function jsxText(s: string): string {
  return s.replace(/[{}<>]/g, (c) => `{${q(c)}}`).replace(/'/g, "&apos;").replace(/"/g, "&quot;");
}

/** Keep only the named imports actually referenced in `body` (avoids unused-import lint errors). */
export function used(names: string[], body: string): string[] {
  return [...new Set(names)].filter((n) => new RegExp(`(^|[^\\w$.])${n.replace(/\$/g, "\\$")}([^\\w$]|$)`).test(body)).sort();
}

export function importLine(names: string[], from: string, body: string, typeOnly: string[] = []): string {
  const n = used(names, body);
  const t = used(typeOnly, body).filter((x) => !n.includes(x));
  const all = [...n, ...t.map((x) => `type ${x}`)];
  if (!all.length) return "";
  return `import { ${all.join(", ")} } from ${q(from)};\n`;
}

/** Python string literal. */
export const pyq = (s: string): string => JSON.stringify(s);
