/** Directory holding kit source files (`kit/<scope>/<feature>/<target path>`). */
export const KIT_ROOT = fileURLToPath(new URL("../../kit/", import.meta.url));

export interface KitOptions {
  /** The project's current package.json (defaults to the template's). */
  packageJson?: string;
  /** The project's current forge.json (defaults to the template's). */
  forgeJson?: string;
  /** The project's current .env.example (defaults to the template's). */
  envExample?: string;
  /** The project's current requirements.txt (fastapi; defaults to the template's). */
  requirements?: string;
  /** `{{projectName}}`-style substitutions for kit files (CMS seed content etc.). */
  vars?: TemplateVars;
}

const SERVER_ONLY_MARKER = /^\/\/ @forge-kit:server-only\n/m;

function walk(dir: string, root: string, out: string[]): void {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, e.name);
    if (e.isDirectory()) walk(full, root, out);
    else if (e.isFile()) out.push(relative(root, full).split(sep).join(posix.sep));
  }
}

function readTemplateFile(id: TemplateId, path: string): string | undefined {
  const p = join(templateDir(id), path);
  return existsSync(p) ? readFileSync(p, "utf8") : undefined;
}

interface CronJobDef {
  name: string;
  schedule: string;
  imports: string[];
  body: string;
}

function cronJobs(features: KitFeature[], ext: "" | ".js"): CronJobDef[] {
  const jobs: CronJobDef[] = [
    {
      name: "heartbeat",
      schedule: "41 * * * *",
      imports: [],
      body: `async () => {\n      const at = new Date().toISOString();\n      console.log(JSON.stringify({ msg: "cron heartbeat", at }));\n      return { at };\n    }`,
    },
  ];
  if (features.includes("auth")) {
    const db = ext ? "../db/client.js" : "@/db/client";
    const schema = ext ? "../db/auth-schema.js" : "@/db/auth-schema";
    jobs.push({
      name: "cleanup-auth",
      schedule: "17 3 * * *",
      imports: ['import { lt } from "drizzle-orm";', `import { db } from "${db}";`, `import { session, verification } from "${schema}";`],
      body: `async () => {\n      const now = new Date();\n      const sessions = await db.delete(session).where(lt(session.expiresAt, now)).returning({ id: session.id });\n      const tokens = await db.delete(verification).where(lt(verification.expiresAt, now)).returning({ id: verification.id });\n      return { expiredSessions: sessions.length, expiredVerifications: tokens.length };\n    }`,
    });
  }
  return jobs;
}

function cronJobsFile(features: KitFeature[], ext: "" | ".js"): string {
  const jobs = cronJobs(features, ext);
  const imports = [...new Set(jobs.flatMap((j) => j.imports))];
  return `${imports.join("\n")}${imports.length ? "\n\n" : ""}/** Generated by Forge app-kit. Schedules are mirrored into forge.json "crons"; add jobs here. */
export interface CronJob {
  schedule: string;
  run: () => Promise<Record<string, unknown>>;
}

export const cronJobs: Record<string, CronJob> = {
${jobs.map((j) => `  ${JSON.stringify(j.name)}: {\n    schedule: ${JSON.stringify(j.schedule)},\n    run: ${j.body},\n  },`).join("\n")}
};
`;
}

function mergeSlots(specs: TemplateFeatureSpec[]): Required<Omit<SlotContribution, "lang" | "wrap">> & { lang?: string; wraps: Array<[string, string]> } {
  const out = { imports: [] as string[], body: [] as string[], head: [] as string[], wraps: [] as Array<[string, string]>, lang: undefined as string | undefined };
  for (const s of specs) {
    if (!s.slot) continue;
    out.imports.push(...(s.slot.imports ?? []));
    out.body.push(...(s.slot.body ?? []));
    out.head.push(...(s.slot.head ?? []));
    if (s.slot.wrap) out.wraps.push(s.slot.wrap);
    if (s.slot.lang) out.lang = s.slot.lang;
  }
  return out;
}

const GENERATED = "Generated by Forge app-kit from the installed features; regenerated when features change.";

function slotFiles(templateId: TemplateId, features: KitFeature[], specs: TemplateFeatureSpec[]): Record<string, string> {
  const s = mergeSlots(specs);
  const list = features.join(", ") || "none";
  const wrapOpen = s.wraps.map((w) => w[0]).join("");
  const wrapClose = [...s.wraps].reverse().map((w) => w[1]).join("");
  const body = s.body.length ? `<>\n      ${s.body.join("\n      ")}\n    </>` : "null";
  switch (templateId) {
    case "nextjs":
      return {
        "src/kit/slots.tsx": `import type { ReactNode } from "react";
${s.lang ? "" : 'import { site } from "@/lib/site";\n'}${s.imports.join("\n")}${s.imports.length ? "\n" : ""}
/** ${GENERATED} Features: ${list}. */
export async function kitHtmlLang(): Promise<string> {
  return ${s.lang ? `await ${s.lang}` : "site.locale"};
}

export function KitProviders({ children }: { children: ReactNode }) {
  return <>${wrapOpen}{children}${wrapClose}</>;
}

export function KitBody() {
  return ${body};
}
`,
      };
    case "vite-react-ts":
      return {
        "src/kit/slots.tsx": `import type { ReactNode } from "react";
${s.imports.join("\n")}${s.imports.length ? "\n" : ""}
/** ${GENERATED} Features: ${list}. */
export function KitProviders({ children }: { children: ReactNode }) {
  return <>${wrapOpen}{children}${wrapClose}</>;
}

export function KitBody() {
  return ${body};
}
`,
      };
    case "astro-site": {
      const imports = s.imports.join("\n");
      return {
        "src/kit/Head.astro": `---\n// ${GENERATED} Features: ${list}.\n---\n${s.head.join("\n")}\n`,
        "src/kit/Body.astro": `---\n// ${GENERATED} Features: ${list}.\n${imports}\n---\n${s.body.join("\n")}\n`,
      };
    }
    case "hono-api": {
      // Observability middleware must wrap every other route.
      const ordered = [...s.body].sort((a, b) => Number(b.startsWith("mountObservability")) - Number(a.startsWith("mountObservability")));
      return {
        "src/kit/index.ts": `import type { Hono } from "hono";
${s.imports.join("\n")}

/** ${GENERATED} Features: ${list}. */
export function mountKit(${ordered.length ? "app" : "_app"}: Hono): void {
${ordered.map((b) => `  ${b}`).join("\n")}
}
`,
      };
    }
    case "fastapi":
      return {
        "app/kit/__init__.py": `"""${GENERATED}

Features: ${list}.
"""

from fastapi import FastAPI
${s.imports.length ? `\n${[...s.imports].sort().join("\n")}\n` : ""}

def mount_kit(app: FastAPI) -> None:
${s.body.length ? s.body.map((b) => `    ${b}`).join("\n") : "    return None"}
`,
      };
    case "expo":
      return {
        "src/kit/index.ts": `${s.imports.join("\n")}${s.imports.length ? "\n\n" : ""}/** ${GENERATED} Features: ${list}. Called once from app/_layout.tsx. */
export function initKit(): void {
${s.body.map((b) => `  ${b}`).join("\n")}
}
`,
      };
  }
}

function mergePackageJson(raw: string, specs: TemplateFeatureSpec[]): string {
  const pkg = JSON.parse(raw) as Record<string, unknown> & { dependencies?: Record<string, string>; devDependencies?: Record<string, string>; scripts?: Record<string, string> };
  const sort = (o: Record<string, string>) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
  const deps = { ...(pkg.dependencies ?? {}) };
  const dev = { ...(pkg.devDependencies ?? {}) };
  const scripts = { ...(pkg.scripts ?? {}) };
  for (const s of specs) {
    Object.assign(deps, s.dependencies ?? {});
    Object.assign(dev, s.devDependencies ?? {});
    for (const [k, v] of Object.entries(s.scripts ?? {})) scripts[k] ??= v;
  }
  for (const k of Object.keys(deps)) delete dev[k];
  return `${JSON.stringify({ ...pkg, scripts, dependencies: sort(deps), devDependencies: sort(dev) }, null, 2)}\n`;
}

function mergeEnv(base: string, features: KitFeature[], byFeature: Map<KitFeature, TemplateFeatureSpec>): string {
  let out = base.endsWith("\n") || base === "" ? base : `${base}\n`;
  const present = new Set([...out.matchAll(/^([A-Z_][A-Z0-9_]*)=/gm)].map((m) => m[1]));
  for (const f of features) {
    const vars = (byFeature.get(f)?.env ?? []).filter((v: EnvVarSpec) => !present.has(v.name));
    if (!vars.length) continue;
    out += `\n# --- Forge kit: ${f} ---\n`;
    for (const v of vars) {
      out += `# ${v.description}${v.secret ? " (secret)" : ""}\n${v.name}=${v.secret ? "" : (v.example ?? "")}\n`;
      present.add(v.name);
    }
  }
  return out;
}

function kitDoc(templateId: TemplateId, features: KitFeature[], byFeature: Map<KitFeature, TemplateFeatureSpec>, builtin: KitFeature[]): string {
  const rows = features.map((f) => `| \`${f}\` | ${FEATURES[f].description} | ${(byFeature.get(f)?.env ?? []).map((e) => `\`${e.name}\``).join(", ") || "-"} |`);
  return `# Forge app-kit

${GENERATED}

Template: \`${templateId}\`${builtin.length ? ` · built into the template: ${builtin.map((b) => `\`${b}\``).join(", ")}` : ""}

| Feature | What it adds | Env vars |
| ------- | ------------ | -------- |
${rows.join("\n")}

Secrets go in the environment only (see \`.env.example\`); never commit \`.env\`.
${features.includes("db") ? "\nDatabase: run `npm run db:generate` after changing `src/db/*-schema.ts`, then `npm run db:migrate`. `drizzle/0000_forge_rls.sql` installs `forge_enable_owner_rls(table, owner_column)`; call it in a migration for every table with per-user rows and query those tables inside `withUser(db, userId, tx => ...)`. The app's DATABASE_URL role must not be a superuser or have BYPASSRLS.\n" : ""}${features.includes("cron") ? "\nCron: jobs live in the cron jobs file and are mirrored into `forge.json` `crons`; the Forge scheduler calls each path with `Authorization: Bearer $CRON_SECRET`.\n" : ""}${features.includes("cms") ? "\nCMS: editors listed in `CMS_ADMIN_EMAILS` sign in at `/sign-in` and edit content at `/admin`.\n" : ""}${features.includes("ai") ? "\nAI: the gateway client is server-side only. Never expose `FORGE_PROJECT_TOKEN` to the browser.\n" : ""}`;
}

/**
 * Files to write into a generated project to install app-kit features: the kit source files, the
 * regenerated kit slot (wiring), merged package.json / requirements.txt, .env.example and forge.json
 * (features + crons), and KIT.md. Required features are added automatically (auth → db + email,
 * cms → auth + db). Throws BAD_INPUT if the template cannot host a requested feature.
 */
export function kitFilesFor(templateId: string, features: readonly KitFeature[], opts: KitOptions = {}): Record<string, string> {
  if (!isTemplateId(templateId)) throw new ForgeError("NOT_FOUND", `Unknown template "${templateId}"`);
  const requested = z.array(z.enum(KIT_FEATURES)).parse(features);
  const resolved = resolveFeatures(requested);
  const unsupported = resolved.filter((f) => !FEATURES[f].templates[templateId]);
  if (unsupported.length) {
    throw new ForgeError("BAD_INPUT", `Template ${templateId} does not support kit feature(s): ${unsupported.join(", ")}`, { unsupported });
  }
  const builtin = resolved.filter((f) => FEATURES[f].templates[templateId] === "builtin");
  const active = resolved.filter((f) => !builtin.includes(f));
  const byFeature = new Map<KitFeature, TemplateFeatureSpec>();
  for (const f of active) byFeature.set(f, FEATURES[f].templates[templateId] as TemplateFeatureSpec);
  const specs = [...byFeature.values()];
  const pkgForName = opts.packageJson ?? readTemplateFile(templateId, "package.json");
  let fallbackName: string = templateId;
  try {
    const n = pkgForName ? (JSON.parse(pkgForName) as { name?: unknown }).name : undefined;
    if (typeof n === "string" && !n.includes("{{")) fallbackName = n;
  } catch {
    // keep template id
  }
  const vars = resolveVars(opts.vars ?? { projectName: fallbackName });

  const out: Record<string, string> = {};
  for (const spec of specs) {
    for (const dir of spec.dirs) {
      const root = join(KIT_ROOT, dir);
      if (!existsSync(root)) throw new ForgeError("INTERNAL", `Kit dir ${dir} missing`);
      const files: string[] = [];
      walk(root, root, files);
      for (const rel of files) {
        let content = readFileSync(join(root, rel), "utf8");
        content = content.replace(SERVER_ONLY_MARKER, templateId === "nextjs" ? 'import "server-only";\n' : "");
        out[rel] = content;
      }
    }
  }

  Object.assign(out, slotFiles(templateId, active, specs));

  const ext = templateId === "hono-api" ? ".js" : "";
  if (active.includes("db") && (templateId === "nextjs" || templateId === "hono-api")) {
    const exportsList = [active.includes("auth") ? `export * from "./auth-schema${ext}";` : null, active.includes("cms") ? `export * from "./cms-schema${ext}";` : null].filter(Boolean);
    out["src/db/schema.ts"] = `// ${GENERATED}\n// Add app tables in their own files (e.g. ./app-schema.ts) and re-export them here.\n${exportsList.length ? exportsList.join("\n") : "export {};"}\n`;
  }
  if (active.includes("cron") && (templateId === "nextjs" || templateId === "hono-api")) out["src/lib/cron-jobs.ts"] = cronJobsFile(active, ext);

  const manifestRaw = opts.forgeJson ?? readTemplateFile(templateId, "forge.json");
  if (manifestRaw) {
    const manifest = ForgeManifestSchema.parse(JSON.parse(manifestRaw));
    if (templateId === "nextjs" && active.includes("seo")) {
      out["src/lib/seo-routes.ts"] = `// ${GENERATED}\n/** Public routes listed in the sitemap (mirrors forge.json publicRoutes). */\nexport const publicRoutes: readonly string[] = ${JSON.stringify(manifest.publicRoutes)};\n`;
    }
    const featuresAll = [...new Set([...(manifest.features ?? []), ...resolved])].sort();
    let crons: CronSpec[] | undefined = manifest.crons;
    if (active.includes("cron")) {
      const prefix = templateId === "nextjs" ? "/api/cron/" : "/cron/";
      const jobs = templateId === "fastapi" ? [{ name: "heartbeat", schedule: "41 * * * *" }] : cronJobs(active, ext);
      const byName = new Map((crons ?? []).map((c) => [c.name, c]));
      for (const j of jobs) if (!byName.has(j.name)) byName.set(j.name, { name: j.name, schedule: j.schedule, path: `${prefix}${j.name}` });
      crons = [...byName.values()];
    }
    const next = ForgeManifestSchema.parse({ ...manifest, features: featuresAll, ...(crons ? { crons } : {}) });
    out["forge.json"] = `${JSON.stringify(next, null, 2)}\n`;
  }

  const pkgRaw = opts.packageJson ?? readTemplateFile(templateId, "package.json");
  if (pkgRaw) out["package.json"] = mergePackageJson(pkgRaw, specs);

  if (templateId === "fastapi") {
    const base = opts.requirements ?? readTemplateFile(templateId, "requirements.txt") ?? "";
    const lines = base.split("\n").map((l) => l.trim()).filter(Boolean);
    const names = new Set(lines.map((l) => l.split(/[=<>~[]/)[0]?.toLowerCase()));
    for (const r of specs.flatMap((s) => s.requirements ?? [])) {
      const n = r.split(/[=<>~[]/)[0]?.toLowerCase();
      if (!names.has(n)) {
        lines.push(r);
        names.add(n);
      }
    }
    out["requirements.txt"] = `${lines.join("\n")}\n`;
  }

  out[".env.example"] = mergeEnv(opts.envExample ?? readTemplateFile(templateId, ".env.example") ?? "", active, byFeature);
  out["KIT.md"] = kitDoc(templateId, active, byFeature, builtin);
  for (const k of Object.keys(out)) out[k] = substituteForFile(k, out[k] as string, vars);
  return out;
}

/** Env vars a feature set needs in a template (for the platform's secret prompts). */
export function kitEnvVars(templateId: TemplateId, features: readonly KitFeature[]): EnvVarSpec[] {
  const seen = new Map<string, EnvVarSpec>();
  for (const f of resolveFeatures(features)) {
    const spec = FEATURES[f].templates[templateId];
    if (spec && spec !== "builtin") for (const e of spec.env ?? []) if (!seen.has(e.name)) seen.set(e.name, e);
  }
  return [...seen.values()];
}
