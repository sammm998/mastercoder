/**
 * Bundles the Vite plugin (source tags + inspector) into one standalone ESM file that generated
 * projects carry as `forge-visual-edit.mjs` (they cannot install @forge/visual-edit from npm).
 * Writes src/plugin-bundle.ts (committed). Run `pnpm --filter @forge/visual-edit build:plugin`.
 */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");

export async function bundlePlugin(): Promise<string> {
  const r = await build({
    entryPoints: [join(pkg, "src/vite-plugin.ts")],
    bundle: true,
    format: "esm",
    platform: "node",
    target: ["node20"],
    write: false,
    legalComments: "none",
    // Installed in the generated project as devDependencies.
    external: ["vite", "@babel/parser", "magic-string"],
  });
  return r.outputFiles[0]!.text.trim();
}

export function renderPluginModule(code: string): string {
  return [
    "// Generated by scripts/build-plugin.ts from src/vite-plugin.ts. Do not edit.",
    "/** Standalone ESM source of the Forge visual-edit Vite plugin, written into generated projects. */",
    `export const VISUAL_EDIT_PLUGIN_SOURCE: string = ${JSON.stringify(code)};`,
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(pkg, "src/plugin-bundle.ts"), renderPluginModule(await bundlePlugin()));
  console.log("wrote src/plugin-bundle.ts");
}
