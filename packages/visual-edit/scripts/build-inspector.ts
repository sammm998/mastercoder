/**
 * Bundles src/inspector/inspector.ts into a minified IIFE and writes it as a string export to
 * src/inspector-script.ts (committed, so consumers need no build step). A unit test fails if the
 * committed file is stale: run `pnpm --filter @forge/visual-edit build:inspector`.
 */
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");

export async function bundleInspector(): Promise<string> {
  const r = await build({
    entryPoints: [join(pkg, "src/inspector/inspector.ts")],
    bundle: true,
    format: "iife",
    minify: true,
    target: ["es2020"],
    write: false,
    legalComments: "none",
  });
  return r.outputFiles[0]!.text.trim();
}

export function renderModule(code: string): string {
  return [
    "// Generated by scripts/build-inspector.ts from src/inspector/inspector.ts. Do not edit.",
    "/** Minified preview inspector; inject as an inline <script> in the generated app's dev HTML. */",
    `export const INSPECTOR_SCRIPT: string = ${JSON.stringify(code)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const code = await bundleInspector();
  writeFileSync(join(pkg, "src/inspector-script.ts"), renderModule(code));
  console.log(`inspector-script.ts written (${code.length} bytes)`);
}
